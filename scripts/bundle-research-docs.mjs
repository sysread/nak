#!/usr/bin/env node
/**
 * Bundles every Markdown file under `docs/user/` and `docs/dev/` into a
 * Deno-importable TypeScript module the `research_docs` server-side tool
 * loads at request time. The browser-side `src/lib/docs.ts` resolves the
 * same corpora via Vite's `import.meta.glob`; Deno has no equivalent, so
 * we shake the trees here and emit a static module.
 *
 * Output: supabase/functions/venice/_generated/research-docs-corpus.ts
 *
 * The output file is gitignored. Run manually with
 * `mise run bundle-docs`; the dev-start task and the CI deploy step
 * call it automatically before they serve / deploy functions.
 */
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');
const USER_ROOT = join(REPO_ROOT, 'docs/user');
const DEV_ROOT = join(REPO_ROOT, 'docs/dev');
const OUT_DIR = join(REPO_ROOT, 'supabase/functions/venice/_generated');
const OUT_PATH = join(OUT_DIR, 'research-docs-corpus.ts');

function walk(rootDir) {
  const out = [];
  const stack = [rootDir];
  while (stack.length > 0) {
    const dir = stack.pop();
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const ent of entries) {
      const abs = join(dir, ent.name);
      if (ent.isDirectory()) stack.push(abs);
      else if (ent.isFile() && ent.name.endsWith('.md')) out.push(abs);
    }
  }
  return out.sort();
}

function asEntries(rootDir) {
  return walk(rootDir).map((abs) => {
    const rel = relative(rootDir, abs);
    const body = readFileSync(abs, 'utf8');
    return [rel, body];
  });
}

function emit(entries) {
  const lines = [];
  lines.push(`// AUTO-GENERATED by scripts/bundle-research-docs.mjs. Do not edit.`);
  lines.push(`//`);
  lines.push(`// Bundled markdown corpora for the function-side research_docs tool.`);
  lines.push(`// docs/user/ and docs/dev/ get embedded as static strings so the Deno`);
  lines.push(`// edge runtime can compose the sub-completion's system prompt without`);
  lines.push(`// fetching at request time.`);
  lines.push(``);
  lines.push(`export interface BundledDoc {`);
  lines.push(`  /** Path relative to the corpus root (docs/user/ or docs/dev/). */`);
  lines.push(`  readonly path: string;`);
  lines.push(`  /** Raw markdown body, untrimmed. */`);
  lines.push(`  readonly body: string;`);
  lines.push(`}`);
  lines.push(``);

  function emitArr(name, arr) {
    lines.push(`export const ${name}: readonly BundledDoc[] = [`);
    for (const [path, body] of arr) {
      lines.push(`  {`);
      lines.push(`    path: ${JSON.stringify(path)},`);
      lines.push(`    body: ${JSON.stringify(body)},`);
      lines.push(`  },`);
    }
    lines.push(`];`);
    lines.push(``);
  }

  emitArr('USER_DOCS', entries.user);
  emitArr('DEV_DOCS', entries.dev);

  return lines.join('\n');
}

const entries = {
  user: asEntries(USER_ROOT),
  dev: asEntries(DEV_ROOT),
};

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_PATH, emit(entries), 'utf8');

const totalBytes = [...entries.user, ...entries.dev].reduce(
  (n, [, body]) => n + body.length,
  0,
);
console.log(
  `wrote ${relative(REPO_ROOT, OUT_PATH)} ` +
    `(${entries.user.length} user doc(s), ${entries.dev.length} dev doc(s), ` +
    `${(totalBytes / 1024).toFixed(1)} KiB total markdown)`,
);
